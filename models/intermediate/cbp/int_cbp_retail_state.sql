WITH source_data AS (

    SELECT
        STATE_FIPS,
        DATA_YEAR,
        ESTABLISHMENTS,
        EMPLOYMENT,
        EMPLOYMENT_FLAG,
        FIRST_QUARTER_PAYROLL,
        FIRST_QUARTER_PAYROLL_FLAG,
        ANNUAL_PAYROLL,
        ANNUAL_PAYROLL_FLAG
    FROM {{ ref('int_cbp_retail') }}

),

state_retail AS (

    SELECT
        STATE_FIPS,
        DATA_YEAR,

        SUM(ESTABLISHMENTS) AS RETAIL_ESTABLISHMENTS,

        SUM(EMPLOYMENT) AS RETAIL_EMPLOYMENT,

        SUM(FIRST_QUARTER_PAYROLL) AS RETAIL_FIRST_QUARTER_PAYROLL,

        SUM(ANNUAL_PAYROLL) AS RETAIL_ANNUAL_PAYROLL,

        COUNT_IF(EMPLOYMENT_FLAG <> 'G') AS EMPLOYMENT_FLAGGED_ROWS,

        COUNT_IF(FIRST_QUARTER_PAYROLL_FLAG <> 'G')
            AS FIRST_QUARTER_PAYROLL_FLAGGED_ROWS,

        COUNT_IF(ANNUAL_PAYROLL_FLAG <> 'G')
            AS ANNUAL_PAYROLL_FLAGGED_ROWS

    FROM source_data

    GROUP BY
        STATE_FIPS,
        DATA_YEAR

)

SELECT
    STATE_FIPS,
    DATA_YEAR,
    RETAIL_ESTABLISHMENTS,
    RETAIL_EMPLOYMENT,
    RETAIL_FIRST_QUARTER_PAYROLL,
    RETAIL_ANNUAL_PAYROLL,
    EMPLOYMENT_FLAGGED_ROWS,
    FIRST_QUARTER_PAYROLL_FLAGGED_ROWS,
    ANNUAL_PAYROLL_FLAGGED_ROWS

FROM state_retail